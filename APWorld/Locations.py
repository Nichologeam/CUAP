def moodlesanity_locations_enabled(world: "CasualtiesUnknownWorld") -> bool:
    return bool(world.options.Moodlesanity.value != 1)
def skill_locations_enabled(world :"CasualtiesUnknownWorld") -> bool:
    return bool(world.options.Skillsanity)
def crafting_locations_enabled(world :"CasualtiesUnknownWorld") -> bool:
    return bool(world.options.Craftsanity)

def get_total_locations(world: "CasualtiesUnknownWorld") -> int:
    total = 0
    for name in location_table:
        if is_valid_location(world, name):
            total += 1
    return total

def get_location_names() -> Dict[str, int]:
    names = {name: data.ap_code for name, data in location_table.items()}
    return names

def is_valid_location(world: "CasualtiesUnknownWorld", name) -> bool:
    if not moodlesanity_locations_enabled(world) and name in moodlesanity_locations:
        return False
    if name in world.moodlesanity_excluded_locations:
        return False
    if not world.options.GoalRequirement == 3 and name == "Elder Thornback Defeated!":
        return False
    if not skill_locations_enabled(world) and name in skill_locations:
        return False
    if not crafting_locations_enabled(world) and name in crafting_locations:
        return False
    return True

